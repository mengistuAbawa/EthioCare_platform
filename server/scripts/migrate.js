const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const pool = require("../src/config/db");

const migrationsDirectory = path.resolve(__dirname, "../../database/migrations");

const main = async () => {
  await pool.query(`CREATE TABLE IF NOT EXISTS schema_migrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename TEXT NOT NULL UNIQUE,
    checksum TEXT,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`);

  const files = fs.readdirSync(migrationsDirectory)
    .filter((filename) => filename.endsWith(".sql") && !filename.includes("rollback"))
    .sort();

  for (const filename of files) {
    const checksum = crypto.createHash("sha256")
      .update(fs.readFileSync(path.join(migrationsDirectory, filename)))
      .digest("hex");
    const existing = await pool.query(
      "SELECT checksum FROM schema_migrations WHERE filename = $1",
      [filename]
    );
    if (existing.rowCount) {
      if (existing.rows[0].checksum && existing.rows[0].checksum !== checksum) {
        throw new Error(`Migration ${filename} has changed after it was applied.`);
      }
      console.log(`Skipped ${filename} (already applied)`);
      continue;
    }

    const client = await pool.connect();
    try {
      await client.query(fs.readFileSync(path.join(migrationsDirectory, filename), "utf8"));
      await client.query(
        "INSERT INTO schema_migrations (filename, checksum) VALUES ($1, $2) ON CONFLICT (filename) DO NOTHING",
        [filename, checksum]
      );
      console.log(`Applied ${filename}`);
    } catch (error) {
      throw new Error(`Migration failed for ${filename}: ${error.message}`);
    } finally {
      client.release();
    }
  }
};

main()
  .then(() => pool.end())
  .catch((error) => {
    console.error(error.message);
    pool.end().finally(() => process.exit(1));
  });
