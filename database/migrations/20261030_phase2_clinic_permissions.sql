CREATE OR REPLACE FUNCTION set_assessment_clinic_from_doctor()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  assigned_clinic_id BIGINT;
BEGIN
  SELECT d.clinic_id INTO assigned_clinic_id
    FROM doctors d
   WHERE d.id = NEW.doctor_id;
  IF assigned_clinic_id IS NULL THEN
    RAISE EXCEPTION 'Assessment doctor must belong to a clinic';
  END IF;
  NEW.clinic_id = assigned_clinic_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS patient_health_assessments_set_clinic ON patient_health_assessments;
CREATE TRIGGER patient_health_assessments_set_clinic
  BEFORE INSERT OR UPDATE OF doctor_id, clinic_id ON patient_health_assessments
  FOR EACH ROW EXECUTE FUNCTION set_assessment_clinic_from_doctor();

