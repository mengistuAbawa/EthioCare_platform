DECLARE
  orphan_count BIGINT;
BEGIN
  SELECT COUNT(*) INTO orphan_count
    FROM patient_health_assessments
   WHERE clinic_id IS NULL;
  IF orphan_count > 0 THEN
    RAISE EXCEPTION 'Cannot secure Phase 2 assessment isolation: % assessment rows have no clinic relationship', orphan_count;
  END IF;
END;
$$;

ALTER TABLE patient_health_assessments
  ALTER COLUMN clinic_id SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'patient_health_assessments_clinic_doctor_fkey'
       AND conrelid = 'patient_health_assessments'::regclass
  ) THEN
    ALTER TABLE patient_health_assessments
      ADD CONSTRAINT patient_health_assessments_clinic_doctor_fkey
      FOREIGN KEY (doctor_id, clinic_id)
      REFERENCES doctors(id, clinic_id)
      ON DELETE RESTRICT;
  END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS patient_health_assessments_clinic_idx
