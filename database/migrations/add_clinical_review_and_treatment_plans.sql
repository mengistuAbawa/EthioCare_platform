BEGIN;

ALTER TABLE patient_health_assessments
  ADD COLUMN IF NOT EXISTS symptom_onset TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS symptom_duration TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS symptom_frequency TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS severity SMALLINT,
  ADD COLUMN IF NOT EXISTS symptom_trend TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS previous_treatment TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS additional_notes TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS safety_answers JSONB NOT NULL DEFAULT '{}'::jsonb;

ALTER TABLE patient_health_assessments
  ALTER COLUMN ocr_status SET DEFAULT 'not_configured',
  ALTER COLUMN ai_summary_status SET DEFAULT 'not_configured',
  DROP CONSTRAINT IF EXISTS patient_health_assessments_ocr_status_check,
  DROP CONSTRAINT IF EXISTS patient_health_assessments_ai_summary_status_check,
  ADD CONSTRAINT patient_health_assessments_ocr_status_check
    CHECK (ocr_status IN ('not_configured', 'disabled', 'pending', 'completed', 'failed')),
  ADD CONSTRAINT patient_health_assessments_ai_summary_status_check
    CHECK (ai_summary_status IN ('not_configured', 'disabled', 'pending', 'completed', 'failed'));

ALTER TABLE assessment_processing_jobs
  ALTER COLUMN status SET DEFAULT 'not_configured',
  DROP CONSTRAINT IF EXISTS assessment_processing_jobs_status_check,
  ADD CONSTRAINT assessment_processing_jobs_status_check
    CHECK (status IN ('pending', 'completed', 'not_configured', 'disabled', 'failed'));

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'patient_assessment_severity_range'
       AND conrelid = 'patient_health_assessments'::regclass
  ) THEN
    ALTER TABLE patient_health_assessments
      ADD CONSTRAINT patient_assessment_severity_range
      CHECK (severity IS NULL OR severity BETWEEN 0 AND 10);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'patient_assessment_symptom_trend_allowed'
       AND conrelid = 'patient_health_assessments'::regclass
  ) THEN
    ALTER TABLE patient_health_assessments
      ADD CONSTRAINT patient_assessment_symptom_trend_allowed
      CHECK (symptom_trend IN ('', 'improving', 'stable', 'worsening'));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'patient_assessment_safety_answers_object'
       AND conrelid = 'patient_health_assessments'::regclass
  ) THEN
    ALTER TABLE patient_health_assessments
      ADD CONSTRAINT patient_assessment_safety_answers_object
      CHECK (jsonb_typeof(safety_answers) = 'object');
  END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS doctor_assessment_review_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES patient_health_assessments(id) ON DELETE RESTRICT,
  doctor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  version INTEGER NOT NULL CHECK (version > 0),
  review_notes TEXT NOT NULL CHECK (length(trim(review_notes)) BETWEEN 1 AND 10000),
  status TEXT NOT NULL CHECK (status IN ('in_review', 'reviewed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (assessment_id, version)
);

CREATE INDEX IF NOT EXISTS doctor_assessment_review_versions_history_idx
  ON doctor_assessment_review_versions (assessment_id, created_at DESC);

CREATE TABLE IF NOT EXISTS doctor_assessment_lab_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES patient_health_assessments(id) ON DELETE RESTRICT,
  result_index INTEGER NOT NULL CHECK (result_index >= 0),
  doctor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  version INTEGER NOT NULL CHECK (version > 0),
  verification_status TEXT NOT NULL CHECK (verification_status IN ('verified', 'corrected')),
  original_result JSONB NOT NULL CHECK (jsonb_typeof(original_result) = 'object'),
  reviewed_result JSONB NOT NULL CHECK (jsonb_typeof(reviewed_result) = 'object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (assessment_id, result_index, version)
);

CREATE INDEX IF NOT EXISTS doctor_assessment_lab_versions_history_idx
  ON doctor_assessment_lab_versions (assessment_id, result_index, version DESC);

CREATE TABLE IF NOT EXISTS treatment_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES patient_health_assessments(id) ON DELETE RESTRICT,
  doctor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  version INTEGER NOT NULL CHECK (version > 0),
  status TEXT NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'approved', 'superseded', 'cancelled')),
  plan_payload JSONB NOT NULL CHECK (jsonb_typeof(plan_payload) = 'object'),
  approved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (assessment_id, version),
  CHECK (status <> 'approved' OR approved_at IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS treatment_plans_one_approved_per_assessment_idx
  ON treatment_plans (assessment_id)
  WHERE status = 'approved';

CREATE UNIQUE INDEX IF NOT EXISTS treatment_plans_one_draft_per_assessment_idx
  ON treatment_plans (assessment_id)
  WHERE status = 'draft';

CREATE INDEX IF NOT EXISTS treatment_plans_assessment_history_idx
  ON treatment_plans (assessment_id, version DESC);

CREATE OR REPLACE FUNCTION set_treatment_plan_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS treatment_plans_set_updated_at ON treatment_plans;
CREATE TRIGGER treatment_plans_set_updated_at
  BEFORE UPDATE ON treatment_plans
  FOR EACH ROW EXECUTE FUNCTION set_treatment_plan_updated_at();

COMMIT;
