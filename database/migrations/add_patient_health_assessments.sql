BEGIN;

CREATE TABLE IF NOT EXISTS patient_health_assessments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
  chief_complaint TEXT NOT NULL CHECK (length(trim(chief_complaint)) BETWEEN 2 AND 2000),
  symptoms JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(symptoms) = 'array'),
  medical_history TEXT NOT NULL DEFAULT '',
  medications TEXT NOT NULL DEFAULT '',
  allergies TEXT NOT NULL DEFAULT '',
  lab_results JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(lab_results) = 'array'),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (
    status IN ('draft', 'submitted', 'in_review', 'reviewed')
  ),
  review_notes TEXT,
  submitted_at TIMESTAMPTZ,
  reviewed_at TIMESTAMPTZ,
  ocr_status TEXT NOT NULL DEFAULT 'disabled' CHECK (ocr_status IN ('disabled', 'pending', 'completed', 'failed')),
  ai_summary_status TEXT NOT NULL DEFAULT 'disabled' CHECK (ai_summary_status IN ('disabled', 'pending', 'completed', 'failed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS patient_health_assessments_patient_idx
  ON patient_health_assessments (patient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS patient_health_assessments_doctor_idx
  ON patient_health_assessments (doctor_id, status, submitted_at DESC);

CREATE TABLE IF NOT EXISTS assessment_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES patient_health_assessments(id) ON DELETE CASCADE,
  object_key TEXT NOT NULL UNIQUE,
  original_filename TEXT NOT NULL CHECK (length(trim(original_filename)) BETWEEN 1 AND 255),
  content_type TEXT NOT NULL CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')),
  file_size BIGINT NOT NULL CHECK (file_size BETWEEN 1 AND 8388608),
  upload_status TEXT NOT NULL DEFAULT 'pending' CHECK (upload_status IN ('pending', 'uploaded')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (assessment_id, id)
);

CREATE INDEX IF NOT EXISTS assessment_files_assessment_idx
  ON assessment_files (assessment_id, created_at);

CREATE TABLE IF NOT EXISTS assessment_processing_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES patient_health_assessments(id) ON DELETE CASCADE,
  job_type TEXT NOT NULL CHECK (job_type IN ('ocr', 'ai_summary')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'completed', 'disabled', 'failed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  UNIQUE (assessment_id, job_type)
);

CREATE INDEX IF NOT EXISTS assessment_processing_jobs_pending_idx
  ON assessment_processing_jobs (created_at)
  WHERE status = 'pending';

CREATE OR REPLACE FUNCTION set_assessment_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS patient_health_assessments_set_updated_at ON patient_health_assessments;
CREATE TRIGGER patient_health_assessments_set_updated_at
  BEFORE UPDATE ON patient_health_assessments
  FOR EACH ROW EXECUTE FUNCTION set_assessment_updated_at();

COMMIT;
