-- EthioCare PostgreSQL schema, version 1.
-- Requires PostgreSQL 12+ and permission to install the btree_gist extension.
-- This file is additive and repeatable on a clean database. Review existing
-- objects before applying to a database that already contains EthioCare tables.

BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
  email TEXT NOT NULL CHECK (length(trim(email)) > 0),
  password_hash TEXT NOT NULL CHECK (length(password_hash) > 0),
  phone TEXT,
  role TEXT NOT NULL CHECK (
    role IN ('system_admin', 'clinic_admin', 'doctor', 'receptionist', 'patient')
  ),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_verified BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, role)
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_uidx ON users (lower(email));
CREATE INDEX IF NOT EXISTS users_role_active_idx ON users (role, is_active);

CREATE TABLE IF NOT EXISTS platform_settings (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  platform_name TEXT NOT NULL DEFAULT 'EthioCare'
    CHECK (length(trim(platform_name)) BETWEEN 2 AND 120),
  contact_email TEXT,
  contact_phone TEXT,
  patient_registration_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  clinic_approval_required BOOLEAN NOT NULL DEFAULT TRUE,
  max_booking_days INTEGER NOT NULL DEFAULT 2 CHECK (max_booking_days BETWEEN 1 AND 365),
  min_booking_lead_hours INTEGER NOT NULL DEFAULT 2 CHECK (min_booking_lead_hours BETWEEN 0 AND 720),
  cancellation_cutoff_hours INTEGER NOT NULL DEFAULT 24 CHECK (cancellation_cutoff_hours BETWEEN 0 AND 720),
  notify_appointment_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  notify_general_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  maintenance_mode BOOLEAN NOT NULL DEFAULT FALSE,
  maintenance_message TEXT NOT NULL DEFAULT 'EthioCare is temporarily unavailable for maintenance. Please try again later.'
    CHECK (length(trim(maintenance_message)) BETWEEN 5 AND 500),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO platform_settings (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS clinics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE CHECK (length(trim(slug)) > 0),
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  contact_email TEXT,
  contact_phone TEXT,
  city TEXT NOT NULL CHECK (length(trim(city)) > 0),
  region TEXT,
  address TEXT NOT NULL CHECK (length(trim(address)) > 0),
  verification_status TEXT NOT NULL DEFAULT 'pending' CHECK (
    verification_status IN ('pending', 'verified', 'rejected')
  ),
  operational_status TEXT NOT NULL DEFAULT 'active' CHECK (
    operational_status IN ('active', 'suspended')
  ),
  reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  rejection_reason TEXT,
  suspended_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  suspended_at TIMESTAMPTZ,
  suspension_reason TEXT,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS clinics_city_region_idx ON clinics (city, region);
CREATE INDEX IF NOT EXISTS clinics_verification_status_idx ON clinics (verification_status);
CREATE INDEX IF NOT EXISTS clinics_operational_status_idx ON clinics (operational_status, verification_status);

CREATE TABLE IF NOT EXISTS clinic_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  role TEXT NOT NULL CHECK (role IN ('clinic_admin', 'receptionist')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (clinic_id, user_id),
  FOREIGN KEY (user_id, role) REFERENCES users(id, role) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS clinic_members_user_active_idx ON clinic_members (user_id, is_active);

CREATE TABLE IF NOT EXISTS doctors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE,
  account_role TEXT NOT NULL DEFAULT 'doctor' CHECK (account_role = 'doctor'),
  clinic_id BIGINT NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  specialty TEXT NOT NULL CHECK (length(trim(specialty)) > 0),
  qualifications TEXT,
  license_number TEXT NOT NULL UNIQUE CHECK (length(trim(license_number)) > 0),
  consultation_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (consultation_fee >= 0),
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_profile_approved BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, clinic_id),
  FOREIGN KEY (user_id, account_role) REFERENCES users(id, role) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS doctors_clinic_specialty_idx ON doctors (clinic_id, specialty);
CREATE INDEX IF NOT EXISTS doctors_available_idx ON doctors (clinic_id, is_available);
CREATE INDEX IF NOT EXISTS doctors_active_clinic_idx ON doctors (clinic_id, is_active, is_available);

CREATE TABLE IF NOT EXISTS services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinic_id BIGINT NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  description TEXT,
  fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fee >= 0),
  duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (clinic_id, name),
  UNIQUE (id, clinic_id)
);

CREATE INDEX IF NOT EXISTS services_clinic_active_idx ON services (clinic_id, is_active);

CREATE TABLE IF NOT EXISTS doctor_services (
  doctor_id BIGINT NOT NULL,
  service_id BIGINT NOT NULL,
  clinic_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (doctor_id, service_id),
  FOREIGN KEY (doctor_id, clinic_id) REFERENCES doctors(id, clinic_id) ON DELETE RESTRICT,
  FOREIGN KEY (service_id, clinic_id) REFERENCES services(id, clinic_id) ON DELETE RESTRICT,
  UNIQUE (doctor_id, service_id, clinic_id)
);

CREATE INDEX IF NOT EXISTS doctor_services_service_idx ON doctor_services (service_id);
CREATE INDEX IF NOT EXISTS doctor_services_active_idx ON doctor_services (doctor_id, is_active);

CREATE TABLE IF NOT EXISTS working_hours (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
  day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (end_time > start_time),
  UNIQUE (doctor_id, day_of_week)
);

CREATE TABLE IF NOT EXISTS time_off (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_id BIGINT NOT NULL REFERENCES doctors(id) ON DELETE RESTRICT,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (ends_at > starts_at)
);

CREATE INDEX IF NOT EXISTS time_off_doctor_period_idx
  ON time_off USING GIST (doctor_id, tstzrange(starts_at, ends_at, '[)'));

CREATE TABLE IF NOT EXISTS appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id BIGINT NOT NULL,
  patient_role TEXT NOT NULL DEFAULT 'patient' CHECK (patient_role = 'patient'),
  doctor_id BIGINT NOT NULL,
  clinic_id BIGINT NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  service_id BIGINT NOT NULL,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (
    status IN ('pending', 'confirmed', 'completed', 'cancelled', 'rejected', 'no_show')
  ),
  reason TEXT,
  cancellation_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (ends_at > starts_at),
  FOREIGN KEY (patient_id, patient_role) REFERENCES users(id, role) ON DELETE RESTRICT,
  FOREIGN KEY (doctor_id, clinic_id) REFERENCES doctors(id, clinic_id) ON DELETE RESTRICT,
  FOREIGN KEY (service_id, clinic_id) REFERENCES services(id, clinic_id) ON DELETE RESTRICT,
  FOREIGN KEY (doctor_id, service_id, clinic_id)
    REFERENCES doctor_services(doctor_id, service_id, clinic_id) ON DELETE RESTRICT,
  CONSTRAINT appointments_doctor_no_active_overlap
    EXCLUDE USING GIST (
      doctor_id WITH =,
      tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status IN ('pending', 'confirmed')),
  CONSTRAINT appointments_patient_no_active_overlap
    EXCLUDE USING GIST (
      patient_id WITH =,
      tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status IN ('pending', 'confirmed'))
);

CREATE INDEX IF NOT EXISTS appointments_patient_start_idx ON appointments (patient_id, starts_at DESC);
CREATE INDEX IF NOT EXISTS appointments_doctor_start_idx ON appointments (doctor_id, starts_at DESC);
CREATE INDEX IF NOT EXISTS appointments_clinic_start_idx ON appointments (clinic_id, starts_at DESC);
CREATE INDEX IF NOT EXISTS appointments_status_start_idx ON appointments (status, starts_at);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  appointment_id BIGINT REFERENCES appointments(id) ON DELETE SET NULL,
  title TEXT NOT NULL CHECK (length(trim(title)) > 0),
  message TEXT NOT NULL CHECK (length(trim(message)) > 0),
  type TEXT NOT NULL CHECK (type IN ('appointment', 'system', 'general')),
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS notifications_recipient_unread_idx
  ON notifications (recipient_id, created_at DESC) WHERE (is_read = FALSE);
CREATE INDEX IF NOT EXISTS notifications_appointment_idx ON notifications (appointment_id);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL CHECK (length(trim(action)) > 0),
  entity TEXT NOT NULL CHECK (length(trim(entity)) > 0),
  entity_id TEXT,
  ip_address INET,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_logs_actor_created_idx ON audit_logs (actor_id, created_at DESC);
CREATE INDEX IF NOT EXISTS audit_logs_entity_idx ON audit_logs (entity, entity_id);
CREATE INDEX IF NOT EXISTS audit_logs_created_idx ON audit_logs (created_at DESC);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DO $$
DECLARE
  table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'clinics', 'clinic_members', 'doctors', 'services',
    'working_hours', 'time_off', 'appointments'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', table_name || '_set_updated_at', table_name);
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      table_name || '_set_updated_at', table_name
    );
  END LOOP;
END;
$$;

COMMIT;